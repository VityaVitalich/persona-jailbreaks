#!/usr/bin/env python3
"""
Emit tables/steering_gemma.tex -- the Gemma-4-31B counterpart of tab:attack, from
results/gemma_steering_cell_cis.json (extract_gemma_steering_cells.py) plus the
standard-attack cells in results/gemma_steering_cell_cis_classic.json.

Conventions carried over from tables/steering_llama.tex: steering rows first (safety-relevant
directions, then individual traits), standard attacks last, benchmarks as columns. HarmBench is
the Gemma-refused group, JBB the 100 raw behaviours, WildJB the refused-only subset.

Cells that have not finished are printed as `--`, never as a partial number: while an arm runs,
its results.jsonl holds only the pairs that already flipped. Trait rows carry the steered sign,
because 6 of the 10 most predictive Gemma traits predict jailbreak with a negative sign and are
steered along their negative pole (see the bundle meta).

Usage: python3 full_trait_tools/build_gemma_steering_table.py [--cite-cmd citep] [--out PATH]
"""
import argparse
import json
from pathlib import Path

import torch

REPO = Path(__file__).resolve().parents[1]
VEC = [("w_persona__full", r"PersonaJB Direction"),
       ("refusal_pos1_neg__full", r"Refusal direction ($-r$)"),
       ("dmu__full", r"Jailbreak direction ($\Delta\mu$)")]
EXTRA = [("w_raw__full", r"Steer on $w$ (raw)")]
CONTROLS = [("random_full_s0__full", r"Random (full space)"),
            ("random_persona_s0__full", r"Random (persona space)")]
STD = ["GPTFuzz", "GCG", "PAIR", "PAP", "PEZ"]
BENCH = [("harmbench", "HarmBench"), ("jbb", "JBB (vanilla)"), ("wildjb_refused", "WildJB (adv)")]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--cis", default=str(REPO / "results/gemma_steering_cell_cis.json"))
    p.add_argument("--classic", default=str(REPO / "results/gemma_steering_cell_cis_classic.json"))
    p.add_argument("--bundle", default=str(REPO / "full_trait_output/gemma_steering_inputs/steering_directions_gemma_layer30.pt"))
    p.add_argument("--out", default=str(REPO / "full_trait_output/tables/steering_gemma.tex"))
    p.add_argument("--ci", action="store_true", help="append the 95%% bootstrap CI to each cell")
    p.add_argument("--coherent", action="store_true",
                   help="report ASR over non-degenerate responses and add a degeneracy column "
                        "(some Gemma directions break the model: stoib(-) is 51%% degenerate)")
    a = p.parse_args()

    cis = json.load(open(a.cis))
    cis.update(json.load(open(a.classic)))
    meta = torch.load(a.bundle, map_location="cpu", weights_only=False)["meta"]
    traits = [(k, m) for k, m in meta.items() if k.startswith("trait__")]

    def row(key, label):
        cells = []
        for bkey, _ in BENCH:
            d = cis.get(f"{key}|{bkey}")
            if d is None or not d.get("complete", True):
                cells.append("--")
                if a.coherent:
                    cells.append("--")
                continue
            # the standard-attack cells come from the detection response dumps: no degeneracy
            # label exists for them, so they keep their raw ASR and print "n/a" for degeneracy
            v = d["asr_coherent"] if a.coherent and "asr_coherent" in d else d["asr"]
            lo, hi = ((d["coherent_lo"], d["coherent_hi"]) if a.coherent and "coherent_lo" in d
                      else (d["lo"], d["hi"]))
            cells.append(f"${v:.3f}_{{[{lo:.2f},{hi:.2f}]}}$" if a.ci else f"{v:.3f}")
            if a.coherent:
                cells.append(f"{d['n_degenerate'] / max(d['n_pairs'], 1):.0%}".replace("%", r"\%")
                             if "n_degenerate" in d else "n/a")
        return f"    {label} & " + " & ".join(cells) + r" \\"

    lines = [r"% Generated by full_trait_tools/build_gemma_steering_table.py -- do not edit by hand.",
             r"% Every number comes from results/gemma_steering_cell_cis{,_classic}.json;",
             r"% `--` means that run has not finished, never a partial value.",
             r"\begin{table}", r"  \caption{\claudewritten{Steering attack vs.\ standard attacks on",
             r"  Gemma-4-31B (attack success rate), layer 30. Protocol matches",
             r"  Table~\ref{tab:attack}: the unit-norm direction is added to the residual stream as",
             r"  $\alpha \cdot 258.09 \cdot v$ at every token, $\alpha$ escalated through",
             r"  $\{0.1,\dots,0.5\}$, and a prompt counts as jailbroken if any $\alpha$ in that range",
             r"  flips it. HarmBench reports the originally-refused group, JBB the raw behaviours,",
             r"  WildJB the refused-only subset. Trait rows give the steered pole: six of the ten",
             r"  most predictive Gemma traits predict jailbreaking with a negative sign, so they are",
             r"  steered along their negative direction.}}",
             r"  \label{tab:attack-gemma}", r"  \centering", r"  \small",
             r"  \begin{tabular}{l" + ("cc" if a.coherent else "c") * len(BENCH) + "}", r"    \toprule",
             r"    Attack & " + " & ".join((t + r" & deg.") if a.coherent else t for _, t in BENCH) + r" \\",
             r"    \midrule"]
    for k, lab in VEC:
        lines.append(row(k, lab))
    lines.append(r"    \midrule")
    for k, m in traits:
        t = m["trait"].replace("_", r"\_")
        lines.append(row(k, f"{t} ({'+' if m['sign'] > 0 else '--'})"))
    lines.append(r"    \midrule")
    for k, lab in EXTRA + CONTROLS:
        lines.append(row(k, lab))
    lines.append(r"    \midrule")
    for fam in STD:
        lines.append(row(fam, fam))
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]

    out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    n_done = sum(1 for l in lines if l.startswith("    ") and "--" not in l and "&" in l and "Attack" not in l)
    print("\n".join(lines))
    print(f"\nwrote {out}  ({n_done} fully-populated rows)")


if __name__ == "__main__":
    main()
